/** Approval is external evidence supplied by the operator, never generated by this loader. */
export function cdciApproval(raw: unknown, report: CdciReview) {
  const review = object(raw, ["packageSha256", "licenceSha256", "mappingVersion", "reviewReference", "snomedAffiliateReference", "indiaDeploymentAndUsersConfirmed", "commercialStorageAndRedistributionApproved", "excludedBrandIds"]);
  if (review.packageSha256 !== report.packageSha256 || review.licenceSha256 !== report.licenceSha256 || review.mappingVersion !== CDCI_MAPPING_VERSION) throw new CommandError(409, "Rights review must match this exact package, licence and mapping version");
  if (review.commercialStorageAndRedistributionApproved !== true || review.indiaDeploymentAndUsersConfirmed !== true) throw new CommandError(403, "CDCI publication requires reviewed commercial rights and India deployment/user scope");
  const snomedAffiliateReference = text(review.snomedAffiliateReference, "actual SNOMED affiliate or written NRCeS permission reference", 3, 200);
  const reviewReference = text(review.reviewReference, "rights review reference", 3, 200);
  if (!Array.isArray(review.excludedBrandIds) || review.excludedBrandIds.length !== report.rejected || review.excludedBrandIds.some((id: unknown) => typeof id !== "string" || !/^\d{1,30}$/.test(id))) throw new CommandError(409, "Explicitly review and list every rejected source ID before publishing valid products");
  const excludedBrandIds = new Set<string>(review.excludedBrandIds);
  if (excludedBrandIds.size !== report.rejected || report.rejectedSourceIds.some(id => !excludedBrandIds.has(id))) throw new CommandError(409, "Explicitly review and list every rejected source ID before publishing valid products");
  return { snomedAffiliateReference, reviewReference, excludedBrandIds };
}

/** A preparation aid, not evidence of approval. All rights gates remain false. */
export function cdciReviewDraft(report: CdciReview) {
  return { packageSha256: report.packageSha256, licenceSha256: report.licenceSha256, mappingVersion: report.mappingVersion,
    reviewReference: "", snomedAffiliateReference: "", indiaDeploymentAndUsersConfirmed: false,
    commercialStorageAndRedistributionApproved: false, excludedBrandIds: [...report.rejectedSourceIds] };
}

export async function runCdciImport(args = process.argv.slice(2)) {
  if (!args.length || args.includes("--help")) {
    console.log("Usage: node scripts/import-pharmacy-cdci.ts <package.zip> [--report=<json-path>] [--draft-review=<new-json-path>] [--check --actor=<root-id> [--review=<approved-json>]] [--apply --actor=<root-id> --release=<release-id> --review=<approved-json>]. Default validates without a database connection. Drafts do not grant rights. Check reads database readiness without writes. Check/apply require operator-selected MONGODB_URI. Apply requires prepared indexes, actual rights evidence, India-only scope and reviewed exclusions. No stock or branch medicine is created."); return;
  }
  const [file, ...flags] = args;
  const options = new Map<string, string>();
  for (const flag of flags) {
    const match = /^--(report|draft-review|actor|release|review)=(.+)$/.exec(flag);
    const key = flag === "--apply" ? "apply" : flag === "--check" ? "check" : match?.[1];
    if (!key || options.has(key)) throw new CommandError(400, "Unsupported or repeated CDCI import argument");
    options.set(key, flag === "--apply" || flag === "--check" ? "true" : match![2]);
  }
  if (options.has("check") && options.has("apply")) throw new CommandError(400, "Choose either read-only --check or --apply");
  const outputs = [options.get("report"), options.get("draft-review")].filter((path): path is string => Boolean(path)).map(path => resolve(path));
  const inputs = [file, options.get("review")].filter((path): path is string => Boolean(path)).map(path => resolve(path));
  // Check all paths before creating either artifact. Exclusive creation also protects aliases/existing evidence.
  if (new Set(outputs).size !== outputs.length || outputs.some(path => inputs.includes(path))) throw new CommandError(400, "Report and draft must use different new paths, separate from source and approval files");
  if ((await stat(file)).size > CDCI_LIMITS.compressedBytes) throw new CommandError(400, "CDCI package exceeds 32 MB");
  const started = performance.now(), bytes = await readFile(file), data = readCdciPackage(bytes), report = inspectCdciPackage(data);
  if (options.has("report")) {
    await writeFile(resolve(options.get("report")!), JSON.stringify(report, null, 2) + "\n", { flag: "wx", mode: 0o600 });
  }
  if (options.has("draft-review")) await writeFile(resolve(options.get("draft-review")!), JSON.stringify(cdciReviewDraft(report), null, 2) + "\n", { flag: "wx", mode: 0o600 });
  console.log(JSON.stringify({ ...report, validationMilliseconds: Math.round(performance.now() - started) }));
  if (!options.has("apply") && !options.has("check")) return report;
  if (!options.has("actor") || !process.env.MONGODB_URI || options.has("apply") && (!options.has("review") || !options.has("release"))) throw new CommandError(428, "Check requires a root actor and operator-selected MONGODB_URI; apply also requires an actual release ID and rights-review file");
  const actorId = identifier(options.get("actor"));
  let review: ReturnType<typeof cdciApproval> | undefined;
  if (options.has("review")) {
    const reviewPath = options.get("review")!;
    if ((await stat(reviewPath)).size > 8_000_000) throw new CommandError(400, "Rights-review document is too large");
    review = cdciApproval(JSON.parse(await readFile(reviewPath, "utf8")), report);
  }
  const release = options.has("release") ? text(options.get("release"), "actual release ID", 1, 200) : "";
  const totals = { created: 0, updated: 0, unchanged: 0, excluded: 0 };
  try {
    await mongoose.connect(process.env.MONGODB_URI, { autoIndex: false, autoCreate: false, serverSelectionTimeoutMS: 10000, connectTimeoutMS: 10000 });
    const hello = await mongoose.connection.db!.admin().command({ hello: 1 });
    const transactionCapable = Boolean(hello.setName || hello.msg === "isdbgrid");
    const actorReady = Boolean(await User.exists({ _id: actorId, role: "root", deletedAt: null, isActive: { $ne: false } }));
    const readiness = await inspectDatabaseIndexes([PharmacyGlobalProduct, Medicine, User, AuditLog, AuditChainHead]);
    const ready = readiness.ready && transactionCapable && actorReady && Boolean(review);
    if (options.has("check")) {
      const result = { mode: "check" as const, ready, databaseChanged: false, transactionCapable, actorReady, rightsReady: Boolean(review), indexes: readiness,
        packageSha256: report.packageSha256, importable: report.importable, rejected: report.rejected };
      console.log(JSON.stringify(result)); return result;
    }
    if (!transactionCapable) throw new CommandError(409, "Catalogue ingestion requires a transaction-capable MongoDB replica set or managed cluster");
    if (!actorReady) throw new CommandError(403, "An active root operator is required for shared catalogue ingestion");
    if (!readiness.ready) throw new CommandError(409, "Prepare catalogue, medicine and audit indexes using the existing database setup before importing");
    const approved = review!; // Apply prerequisites and evidence were checked before connecting.
    let batch: ReturnType<typeof mapCdciBrand>[] = [];
    const flush = async () => {
      if (!batch.length) return;
      const result = await ingestReviewedCatalogue({ provider: "cdci", release, reference: `NRCeS CDCI ${data.packageSha256}; ${CDCI_MAPPING_VERSION}`,
        licenceSha256: data.licenceSha256, reviewReference: `${approved.reviewReference}; affiliate: ${approved.snomedAffiliateReference}`,
        snomedAffiliateReference: approved.snomedAffiliateReference, indiaDeploymentAndUsersConfirmed: true,
        commercialStorageAndRedistributionApproved: true, products: batch }, actorId, data.packageSha256);
      totals.created += result.created; totals.updated += result.updated; totals.unchanged += result.unchanged;
      batch = [];
    };
    for (const brand of data.tables["BrandMaster.txt"].values()) {
      let product: ReturnType<typeof mapCdciBrand>;
      try { product = mapCdciBrand(data, brand); }
      catch (error) {
        if (!(error instanceof CommandError) || !approved.excludedBrandIds.has(brand.Identifier)) throw error;
        totals.excluded++; continue;
      }
      if (approved.excludedBrandIds.has(brand.Identifier)) throw new CommandError(409, "Rights review excludes a valid row; recheck the exact rejection manifest");
      batch.push(product); if (batch.length === 200) { await flush(); console.log(JSON.stringify({ progress: true, ...totals })); }
    }
    await flush();
    console.log(JSON.stringify({ completed: true, packageSha256: data.packageSha256, release, ...totals }));
    return totals;
  } finally { await mongoose.disconnect(); }
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) runCdciImport().then(result => {
  if (result && "mode" in result && !result.ready) process.exitCode = 2;
}).catch(error => {
  console.error(error instanceof CommandError ? error.message : "CDCI import failed. Check the retained report and source batch results; credentials and record values are omitted. Safe retries reuse the same source IDs."); process.exitCode = 1;
});
