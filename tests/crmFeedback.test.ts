import crypto from 'node:crypto';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { app } from '../index.ts';
import { Organization } from '../models/Organization.ts';
import { Location } from '../models/Location.ts';
import { OrgMember } from '../models/OrgMember.ts';
import { User } from '../models/User.ts';
import { Patient } from '../models/Patient.ts';
import { Appointment } from '../models/Appointment.ts';
import { PatientFeedback } from '../models/PatientFeedback.ts';
import { PatientRelationship } from '../models/PatientRelationship.ts';
import { TaskModel } from '../models/Task.ts';
import { CrmActivity } from '../models/CrmActivity.ts';
import { AuditLog } from '../models/AuditLog.ts';
import { DomainEventOutbox } from '../models/DomainEventOutbox.ts';
import { OperationReceipt } from '../models/OperationReceipt.ts';
import { createAuthSession } from '../utilities/helpers.ts';
afterEach(() => vi.restoreAllMocks());
async function fixture() {
  const org = await Organization.create({ name: 'Feedback clinic', city: 'Mumbai', crmSettings: { feedbackRecoveryRating: 3, defaultTaskHours: 12 } });
  const foreign = await Organization.create({ name: 'Other clinic', city: 'Delhi' });
  const branch = await Location.create({ organizationId: org.id, name: 'Visible branch', city: 'Mumbai' });
  const hidden = await Location.create({ organizationId: org.id, name: 'Hidden branch', city: 'Mumbai' });
  const admin = await User.create({ role: 'admin', name: 'Recorder', email: `${crypto.randomUUID()}@example.test` });
  const membership = await OrgMember.create({ organizationId: org.id, userId: admin.id, role: 'admin', locationAccess: { mode: 'all' } });
  const consumer = await User.create({ role: 'patient', name: 'Respondent', email: `${crypto.randomUUID()}@example.test` });
  const patient = await Patient.create({ organizationId: org.id, userId: consumer.id, name: 'Private patient' });
  const otherPatient = await Patient.create({ organizationId: org.id, name: 'Other patient' });
  const cookies = { access_token: (await createAuthSession({ id: admin.id, role: 'admin', email: admin.email!, organization_id: org.id })).accessToken };
  const patientCookies = { access_token: (await createAuthSession({ id: consumer.id, role: 'patient', email: consumer.email! })).accessToken };
  let token = 0;
  const visit = (extra = {}) => Appointment.create({ organizationId: org.id, locationId: branch.id, patientId: patient.id, doctorId: admin.id, appointmentTime: new Date(Date.now() - 86400000), appointmentType: 'reception', status: 'completed', bookingMode: 'sequential_queue', tokenNumber: ++token, ...extra });
  const command = (appointmentId: string, extra = {}) => ({ appointmentId, clientRequestId: crypto.randomUUID(), rating: 3, npsScore: 6, comments: 'Private service comment', ...extra });
  const submit = (payload: Record<string, unknown>, credentials = cookies) => app.inject({ method: 'POST', url: '/api/feedback', cookies: credentials, payload });
  const get = (path: string, credentials = cookies) => app.inject({ method: 'GET', url: `/api/feedback${path}`, cookies: credentials });
  return { org, foreign, branch, hidden, admin, membership, consumer, patient, otherPatient, cookies, patientCookies, visit, command, submit, get };
}
describe('Canonical feedback and service recovery', () => {
  it('commits one attributable survey, encrypted comment, recovery task, audit and receipt on exact concurrent retries', async () => {
    const f = await fixture(), visit = await f.visit();
    await PatientRelationship.create({ organizationId: f.org.id, patientId: f.patient.id, locationId: f.branch.id, ownerId: f.admin.id });
    const command = f.command(visit.id), responses = await Promise.all([f.submit(command), f.submit(command)]);
    expect(responses.map(row => row.statusCode).sort()).toEqual([200, 201]);
    expect(responses[0].json().data.source).toBe('staff_reported');
    expect(await PatientFeedback.countDocuments({ appointmentId: visit.id })).toBe(1);
    const raw = await PatientFeedback.collection.findOne({ appointmentId: visit._id }); expect(raw?.comments).toMatch(/^enc:v1:/); expect(raw?.comments).not.toContain('Private service');
    const tasks = await TaskModel.find({ organizationId: f.org.id, kind: 'crm_feedback' }); expect(tasks).toHaveLength(1);
    expect(tasks[0]).toMatchObject({ title: 'Review visit feedback', needsAssignment: false }); expect(String(tasks[0].assignedTo)).toBe(f.admin.id);
    expect(tasks[0].dueDate!.getTime() - Date.now()).toBeGreaterThan(11.9 * 3600000);
    expect(JSON.stringify(tasks)).not.toContain('Private service');
    expect(await AuditLog.countDocuments({ targetId: responses[0].json().data.id, action: 'PATIENT_FEEDBACK_SUBMIT' })).toBe(1);
    expect(await CrmActivity.countDocuments({ organizationId: f.org.id, kind: 'feedback_recorded' })).toBe(1);
    expect(await OperationReceipt.countDocuments({ scope: `feedback:${f.admin.id}`, key: command.clientRequestId })).toBe(1);
    expect((await f.submit({ ...command, rating: 4 })).statusCode).toBe(409);
    expect((await f.get(`/visit/${visit.id}`)).json().data.comments).toBe(command.comments);
    expect((await f.get('')).body).not.toContain(command.comments);
  });
  it('rolls back survey, task, activity, notification and receipt after audit failure', async () => {
    const f = await fixture(), visit = await f.visit(), command = f.command(visit.id);
    await PatientRelationship.create({ organizationId: f.org.id, patientId: f.patient.id, locationId: f.branch.id, ownerId: f.admin.id });
    vi.spyOn(AuditLog, 'create').mockRejectedValueOnce(new Error('audit unavailable'));
    expect((await f.submit(command)).statusCode).toBe(503);
    expect(await PatientFeedback.countDocuments({ appointmentId: visit.id })).toBe(0);
    expect(await TaskModel.countDocuments({ organizationId: f.org.id })).toBe(0);
    expect(await CrmActivity.countDocuments({ organizationId: f.org.id })).toBe(0);
    expect(await DomainEventOutbox.countDocuments({ organizationId: f.org.id })).toBe(0);
    expect(await OperationReceipt.countDocuments({ key: command.clientRequestId })).toBe(0);
    expect((await f.submit(command)).statusCode).toBe(201);
  });
  it('requires actual self ownership and completion; family, guest and another patient cannot submit', async () => {
    const f = await fixture(), own = await f.visit(), another = await f.visit({ patientId: f.otherPatient.id }), pending = await f.visit({ status: 'confirmed' });
    expect((await f.submit(f.command(another.id), f.patientCookies)).statusCode).toBe(403);
    expect((await f.submit(f.command(pending.id), f.patientCookies)).statusCode).toBe(409);
    const family = await User.create({ role: 'family_member', name: 'Relative', email: `${crypto.randomUUID()}@example.test` });
    const credentials = { access_token: (await createAuthSession({ id: family.id, role: 'family_member', email: family.email! })).accessToken };
    expect((await f.submit(f.command(own.id), credentials)).statusCode).toBe(403);
    const response = await f.submit(f.command(own.id, { rating: 5 }), f.patientCookies); expect(response.statusCode, response.body).toBe(201);
    expect(response.json().data.source).toBe('patient_submitted');
    expect(await TaskModel.countDocuments({ organizationId: f.org.id })).toBe(0);
    expect((await f.get(`/visit/${own.id}`, f.patientCookies)).statusCode).toBe(200);
    const mine = await f.get('/mine', f.patientCookies); expect(mine.json().data.map((row: any) => row.appointmentId)).toEqual([own.id]);
    expect((await f.get('/mine', credentials)).statusCode).toBe(403);
    expect((await f.get('/stats', f.patientCookies)).statusCode).toBe(403);
  });
  it('enforces strict selected branches and tenant boundaries for writes, detail, reports and eligible visits', async () => {
    const f = await fixture(), visible = await f.visit(), hidden = await f.visit({ locationId: f.hidden.id }), foreign = await f.visit({ organizationId: f.foreign.id });
    await OrgMember.updateOne({ _id: f.membership.id }, { locationAccess: { mode: 'selected', locationIds: [f.branch.id] } });
    expect((await f.submit(f.command(hidden.id))).statusCode).toBe(404);
    expect((await f.submit(f.command(foreign.id))).statusCode).toBe(404);
    expect((await f.get(`/visit/${hidden.id}`)).statusCode).toBe(404);
    expect((await f.get(`/stats?locationId=${f.hidden.id}`)).statusCode).toBe(404);
    const eligible = await f.get('/eligible-visits'); expect(eligible.statusCode, eligible.body).toBe(200);
    expect(eligible.json().data.items.map((row: any) => row.id)).toEqual([visible.id]);
    expect(eligible.body).not.toContain('Private patient');
    await OrgMember.updateOne({ _id: f.membership.id }, { locationAccess: { mode: 'selected', locationIds: [] } });
    expect((await f.get('/stats')).statusCode).toBe(403);
    expect((await f.submit(f.command(visible.id))).statusCode).toBe(403);
  });
  it('reconciles legacy feedback without relabeling or returning private text; empty scores are unavailable', async () => {
    const f = await fixture(); const empty = await f.get('/stats'); expect(empty.json().data).toMatchObject({ totalResponses: 0, averageCsatRating: null, netPromoterScore: null });
    const own = await f.visit(), foreign = await f.visit({ organizationId: f.foreign.id });
    for (const visit of [own, foreign]) await PatientFeedback.create({ appointmentId: visit.id, locationId: visit.locationId, patientId: visit.patientId, doctorId: visit.doctorId, rating: 2, npsScore: 4, comments: 'Hidden legacy text' });
    const report = await f.get('/stats'); expect(report.json().data.totalResponses).toBe(1); expect(report.json().data.sources[0].source).toBe('unknown');
    expect(report.body).not.toContain('Hidden legacy text');
    expect((await PatientFeedback.findOne({ appointmentId: own.id }))?.organizationId).toBeUndefined();
  });
  it('bounds eligible pages, excludes recorded visits and rejects fractional ratings', async () => {
    const f = await fixture(), own = await f.visit();
    expect((await f.submit(f.command(own.id, { rating: 2.5 }))).statusCode).toBe(400);
    await Promise.all(Array.from({ length: 22 }, () => f.visit()));
    const first = (await f.get('/eligible-visits')).json().data; expect(first.items).toHaveLength(20); expect(first.nextCursor).toBeTruthy();
    const second = (await f.get(`/eligible-visits?cursor=${first.nextCursor}`)).json().data; expect(second.items).toHaveLength(3);
    expect((await f.submit(f.command(own.id))).statusCode).toBe(201);
    expect((await f.get('/eligible-visits')).body).not.toContain(own.id);
  });
});
