import type { FastifyInstance } from "fastify";
import { authenticate } from "../middleware/auth.ts";
import { requirePharmacyStaff, requirePharmacyAction } from "../middleware/pharmacyGuard.ts";
import { requireModule } from "../middleware/moduleGuard.ts";
import { listPharmacyParties, listPharmacyPurchases, listPharmacyPurchaseProducts, readPharmacyParty, readPharmacyPurchase, writePharmacyParty, writePharmacyPurchase, postPurchase, receivePurchase, recoverPurchase, listPurchaseReceipts } from "../controllers/pharmacyPurchases.ts";
import { readSupplierReturnSource, previewSupplierReturn, postSupplierReturn, recoverSupplierReturn } from "../controllers/pharmacyPurchaseReturns.ts";
import { purchaseCsvInspection, purchaseCsvPreview, purchaseCsvRemember } from "../controllers/pharmacyPurchaseCsv.ts";
import { listPharmacyShortbook, savePharmacyShortbook } from "../controllers/pharmacyShortbook.ts";
import { purchaseOrderController } from "../controllers/pharmacyPurchaseOrders.ts";
import { supplierCollaborationController as supplierController } from "../controllers/pharmacySupplierCollaboration.ts";
export default async function pharmacyPurchaseRoutes(app: FastifyInstance) {
  const view = { preHandler: [authenticate, requirePharmacyStaff, requireModule("pharmacy"), requirePharmacyAction("viewPurchases")] };
  const manage = { preHandler: [authenticate, requirePharmacyStaff, requireModule("pharmacy"), requirePharmacyAction("managePurchases")] };
  app.get("/api/pharmacy/purchase-orders/:id/collaboration", view, supplierController("supplierCollaboration"));
  app.post("/api/pharmacy/purchase-orders/:id/supplier-link", manage, supplierController("manageSupplierLink"));
  app.post("/api/pharmacy/purchase-orders/:id/supplier-email", { ...manage, config: { rateLimit: { max: 5, timeWindow: "1 minute" } } }, supplierController("emailSupplierLink"));
  app.post("/api/pharmacy/purchase-orders/:id/documents", { ...manage, bodyLimit: 6 * 1024 * 1024 }, supplierController("uploadSupplierDocument"));
  app.get("/api/pharmacy/purchase-orders/:id/document-download", view, supplierController("supplierDocumentDownload"));
  app.get("/api/pharmacy/suppliers/:id/archive", view, supplierController("supplierArchive"));
  const publicOptions = { config: { rateLimit: { max: 30, timeWindow: "1 minute" } } };
  app.post("/api/public/pharmacy-supplier-order/read", publicOptions, supplierController("readPublicSupplierOrder", true));
  app.post("/api/public/pharmacy-supplier-order/respond", publicOptions, supplierController("respondPublicSupplierOrder", true));
  app.post("/api/public/pharmacy-supplier-order/documents", { bodyLimit: 6 * 1024 * 1024, config: { rateLimit: { max: 5, timeWindow: "1 minute" } } }, supplierController("uploadSupplierDocument", true));
  app.post("/api/public/pharmacy-supplier-order/document-download", publicOptions, supplierController("supplierDocumentDownload", true));
  app.get("/api/pharmacy/purchase-orders", view, purchaseOrderController("list"));
  app.get("/api/pharmacy/purchase-order-commands/:key", view, purchaseOrderController("recover"));
  app.get("/api/pharmacy/purchase-orders/:id", view, purchaseOrderController("read"));
  app.get("/api/pharmacy/purchase-orders/:id/history", view, purchaseOrderController("history"));
  app.post("/api/pharmacy/purchase-orders", manage, purchaseOrderController("save"));
  app.put("/api/pharmacy/purchase-orders/:id", manage, purchaseOrderController("save"));
  app.post("/api/pharmacy/purchase-orders/:id/actions", manage, purchaseOrderController("action"));
  app.get("/api/pharmacy/shortbook", view, listPharmacyShortbook);
  app.put("/api/pharmacy/shortbook/:medicineId", manage, savePharmacyShortbook);
  app.get("/api/pharmacy/parties", view, listPharmacyParties);
  app.get("/api/pharmacy/parties/:id", view, readPharmacyParty);
  app.post("/api/pharmacy/parties", manage, writePharmacyParty);
  app.put("/api/pharmacy/parties/:id", manage, writePharmacyParty);
  app.get("/api/pharmacy/purchases", view, listPharmacyPurchases);
  app.get("/api/pharmacy/purchase-products", view, listPharmacyPurchaseProducts);
  app.post("/api/pharmacy/purchase-csv/inspect", manage, purchaseCsvInspection);
  app.post("/api/pharmacy/purchase-csv/preview", manage, purchaseCsvPreview);
  app.put("/api/pharmacy/purchase-csv/profile", manage, purchaseCsvRemember);
  app.get("/api/pharmacy/purchases/:id", view, readPharmacyPurchase);
  app.post("/api/pharmacy/purchases", manage, writePharmacyPurchase);
  app.put("/api/pharmacy/purchases/:id", manage, writePharmacyPurchase);
  app.post("/api/pharmacy/purchases/:id/post", manage, postPurchase);
  app.post("/api/pharmacy/purchases/:id/receipts", { preHandler: [...manage.preHandler, requirePharmacyAction("receiveStock")] }, receivePurchase);
  app.get("/api/pharmacy/purchases/:id/receipts", view, listPurchaseReceipts);
  app.get("/api/pharmacy/purchases/:id/operations/:kind/:key", view, recoverPurchase);
  app.get("/api/pharmacy/purchases/:id/return-source", view, readSupplierReturnSource);
  const returns = { preHandler: [...view.preHandler, requirePharmacyAction("processReturn")] };
  app.post("/api/pharmacy/purchases/:id/returns/quote", returns, previewSupplierReturn);
  app.post("/api/pharmacy/purchases/:id/returns", returns, postSupplierReturn);
  app.get("/api/pharmacy/purchase-return-operations/:key", view, recoverSupplierReturn);
}
